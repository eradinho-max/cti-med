'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('static/index.html','utf8');
const core=fs.readFileSync('static/cti-app-v31.js','utf8');
const cera=fs.readFileSync('static/cera.js','utf8');
const css=fs.readFileSync('static/cera.css','utf8');
assert.equal((html.match(/id="view-cera"/g)||[]).length,1,'CERA must have one independent route');
assert.equal((html.match(/id="ctiCeraHub"/g)||[]).length,1,'CERA must have one root');
assert.ok(html.includes('data-v="cera"'),'Sidebar must link to CERA');
assert.ok(html.includes('data-go="cera"'),'Mobile menu must link to CERA');
assert.ok(html.includes('id="ceraGuide"'),'User guide must exist');
assert.ok(html.includes('<details class="card cera-guide"'),'Guide should be collapsible');
assert.ok(!html.slice(html.indexOf('id="view-reforco"'),html.indexOf('id="view-cera"')).includes('ctiCeraHub'),'Trilhas must not contain CERA');
assert.ok(core.includes("'reforco','cera','segunda'"),'Router must support #cera');
assert.ok(core.includes("if (v === 'cera') window.CTI_CERA?.refresh?.()"),'CERA navigation must render');
assert.ok(core.includes("if (destino === 'cera') mostrar('cera', {substituir:true})"),'Quiz exit must return to CERA');
assert.ok(core.includes("window.treinarArea = (area, tema, returnTo = '')"),'Question trainer must accept CERA return destination');
assert.ok(cera.includes("window.treinarArea(rec.area,rec.theme,'cera')"),'CERA must set quiz return destination');
assert.ok(cera.includes("window.CTI_CERA={open,refresh:render,summary:()=>stats()}"),'Module must expose navigation refresh');
assert.ok(!cera.includes("insertAdjacentElement('afterend',b)"),'Must not dynamically duplicate menus');
assert.ok(!cera.includes("anchor.parentNode.insertBefore(section,anchor)"),'Must not inject CERA into Trilhas');
assert.ok(css.includes('#view-cera .cera-guide-grid'),'Guide must have responsive styles');
console.log('CERA standalone route, guide and integration OK');
